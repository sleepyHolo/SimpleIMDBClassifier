class Model:

    def __init__(self, vocab_size, d_model, num_classes):

        self.embedding = Tensor(
            np.random.randn(vocab_size, d_model) * 0.02,
            requires_grad=True
        )

        self.attn = SelfAttention(d_model)

        self.fc = Tensor(
            np.random.randn(d_model, num_classes) / np.sqrt(d_model),
            requires_grad=True
        )

        self.params = (
            [self.embedding, self.fc]
            + self.attn.params
        )

    def embed(self, x):

        emb = self.embedding.data[x]

        return Tensor(emb, requires_grad=True)

    def forward(self, x):

        x = self.embed(x)

        x = self.attn.forward(x)

        pooled = Tensor(
            x.data.mean(axis=1),
            requires_grad=True
        )

        logits = pooled @ self.fc

        return logits


