class SelfAttention:

    def __init__(self, d_model):

        self.Wq = Tensor(
            np.random.randn(d_model, d_model) / np.sqrt(d_model),
            requires_grad=True
        )

        self.Wk = Tensor(
            np.random.randn(d_model, d_model) / np.sqrt(d_model),
            requires_grad=True
        )

        self.Wv = Tensor(
            np.random.randn(d_model, d_model) / np.sqrt(d_model),
            requires_grad=True
        )

        self.params = [self.Wq, self.Wk, self.Wv]

        self.d_model = d_model

    def forward(self, x):

        Q = x @ self.Wq
        K = x @ self.Wk
        V = x @ self.Wv

        scores = Tensor(
            (Q.data @ K.data.transpose(0, 2, 1))
            / np.sqrt(self.d_model),
            requires_grad=True
        )

        attn = softmax(scores)

        out = Tensor(
            attn.data @ V.data,
            requires_grad=True
        )

        return out


