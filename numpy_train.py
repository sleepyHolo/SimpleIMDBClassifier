def relu(x):
    out = Tensor(
        np.maximum(0, x.data),
        requires_grad=x.requires_grad
    )

    def backward(grad):
        if x.requires_grad:
            x.backward(grad * (x.data > 0))

    out.backward_fn = backward
    return out


def softmax(x):
    exp = np.exp(x.data - np.max(x.data, axis=-1, keepdims=True))
    probs = exp / np.sum(exp, axis=-1, keepdims=True)

    out = Tensor(probs, requires_grad=x.requires_grad)

    def backward(grad):
        if not x.requires_grad:
            return

        dx = np.zeros_like(x.data)

        for i in range(len(probs)):
            p = probs[i].reshape(-1, 1)
            jacobian = np.diagflat(p) - p @ p.T
            dx[i] = jacobian @ grad[i]

        x.backward(dx)

    out.backward_fn = backward
    return out


def cross_entropy(logits, targets):
    probs = softmax(logits)

    batch_size = logits.data.shape[0]

    log_probs = np.log(
        probs.data[np.arange(batch_size), targets] + 1e-8
    )

    loss_val = -np.mean(log_probs)

    out = Tensor(loss_val, requires_grad=True)

    def backward(grad):
        grad_logits = probs.data.copy()

        grad_logits[np.arange(batch_size), targets] -= 1
        grad_logits /= batch_size

        logits.backward(grad * grad_logits)

    out.backward_fn = backward
    return out


