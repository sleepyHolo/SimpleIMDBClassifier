def tokenize(text):
    text = text.lower()
    return text.split()


def build_vocab(texts):
    print("Building vocabulary...")

    counter = Counter()

    for text in texts:
        counter.update(tokenize(text))

    vocab = {
        word: idx + 2
        for idx, (word, _)
        in enumerate(counter.most_common(VOCAB_SIZE - 2))
    }

    vocab["<PAD>"] = 0
    vocab["<UNK>"] = 1
    
    print(f"Vocabulary size: {len(vocab)}")
    
    return vocab


def encode(text, vocab):

    words = tokenize(text)

    ids = [
        vocab.get(w, 1)
        for w in words[:MAX_LEN]
    ]

    while len(ids) < MAX_LEN:
        ids.append(0)

    return np.array(ids)


